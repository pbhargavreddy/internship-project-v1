"""
react.py
--------
ReAct agent: the LLM alternates ``Thought`` / ``Action`` (a JSON tool call)
with tool ``Observation``s until it writes a ``Final Answer``.

Malformed replies (bad JSON, unknown tool, bad args) are fed back as
Observations instead of raising. After ``agent_max_steps`` tool steps the
model is told to answer with what it has.

The loop always runs on the API LLM (Groq). If the turn read uploaded PDFs
(rag_search or summarize_papers returned chunks), the final answer is then
regenerated by the fine-tuned model via :func:`backend.llm.router.generate_pdf_answer`,
with the Groq answer as fallback. Citations on such turns come from the
retrieved chunks, whichever model answered.
"""

