def first_json_object(text: str) -> str | None:
    """The first balanced ``{...}`` in ``text`` (braces inside JSON strings are ignored).

    Returns:
        The object's source text, or ``None`` if there is no ``{`` or it never closes.
    """
    start = text.find("{")
    if start == -1:
        return None
    depth, in_str, escaped = 0, False, False
    for i in range(start, len(text)):
        ch = text[i]
        if in_str:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    return None


def parse_reply(text: str) -> ParsedReply:
    """Parse a ReAct reply. Never raises; problems are returned in ``error``.

    ``Action:`` and ``Final Answer:`` are found anywhere in the reply (whichever comes
    first wins), and the first balanced JSON object after ``Action:`` is the tool call.
    """
    text = _OBS_RE.split(text, maxsplit=1)[0]  # drop any Observation the model hallucinated
    m = _THOUGHT_RE.search(text)
    thought = m.group(1).strip().strip("*").strip() if m else ""  # also drop markdown bold markers
    action, final = _ACTION_RE.search(text), _FINAL_RE.search(text)
    if final and (action is None or final.start() < action.start()):
        return ParsedReply(thought=thought, final=text[final.end():].strip())
    if action is None:
        return ParsedReply(
            thought=thought, incomplete=True,
            error="Reply must contain either 'Action: {...}' or 'Final Answer: ...'.",
        )
    raw = text[action.end():]
    try:
        blob = first_json_object(raw)
        if blob is None:
            msg = "no JSON object found" if "{" not in raw else "unbalanced braces"
            raise json.JSONDecodeError(msg, raw, 0)
        obj = json.loads(blob)
    except json.JSONDecodeError as exc:
        return ParsedReply(
            thought=thought,
            error=f'Invalid Action JSON ({exc.msg}). Use Action: {{"tool": "<name>", "args": {{...}}}}',
        )
    if not isinstance(obj, dict) or not isinstance(obj.get("tool"), str) or not isinstance(obj.get("args", {}), dict):
        return ParsedReply(thought=thought, error='Action must be {"tool": "<name>", "args": {...}}.')
    return ParsedReply(thought=thought, action=ToolCall(tool=obj["tool"], args=obj.get("args", {})))


def extract_citations(answer: str, session: Session) -> list[Citation]:
    """Resolve ``[Doc N, Sec S]`` markers in ``answer`` against the session's sources.

    Unknown doc numbers (hallucinated citations) are dropped with a warning.
    """
    found: list[Citation] = []
    for m in _CITE_RE.finditer(answer):
        n, sec = int(m.group(1)), (m.group(2) or "").strip()
        candidates = [c for c in session.sources if c.doc == n]
        match = next((c for c in candidates if sec and (c.section or "").casefold() == sec.casefold()), None)
        if match is None and candidates:
            match = candidates[0]
        if match is not None and (doc_id := session.doc_id_for(n)) is not None:
            match = match.model_copy(update={"title": session.title_for(doc_id)})  # stored title may be stale
        if match is None:
            doc_id = session.doc_id_for(n)
            if doc_id is None:
                log.warning("Answer cites unknown Doc %d", n)
                continue
            match = Citation(doc=n, title=session.title_for(doc_id), section=sec or None)
        if match not in found:
            found.append(match)
    return found


def _unique_chunks(pairs: Iterable[tuple[int, Chunk]]) -> list[tuple[int, Chunk]]:
    """Drop repeated chunks (same ``chunk_id``), keeping first-seen (best-ranked) order."""
    seen: set[str] = set()
    out = []
    for n, chunk in pairs:
        if chunk.chunk_id not in seen:
            seen.add(chunk.chunk_id)
            out.append((n, chunk))
    return out


def citations_from_chunks(answer: str, retrieved: list[tuple[int, Chunk]], session: Session) -> list[Citation]:
    """Citations built from the retrieved chunks, independent of which model answered.

    Chunks of documents the answer cites as ``[Doc N, ...]`` are kept; when a cited
    section matches a chunk's section, only the matching chunks of that document are
    kept. If the answer cites none of the retrieved documents, the top 4 chunks are cited.
    """
    cited: dict[int, set[str]] = {}
    for m in _CITE_RE.finditer(answer):
        cited.setdefault(int(m.group(1)), set()).add((m.group(2) or "").strip().casefold())
    chunks = [(n, c) for n, c in retrieved if n in cited]
    if chunks:
        matched = {n for n, c in chunks if (c.section or "").casefold() in cited[n]}
        chunks = [(n, c) for n, c in chunks if n not in matched or (c.section or "").casefold() in cited[n]]
    else:
        chunks = retrieved[:4]
    out: list[Citation] = []
    for n, c in chunks:
        cit = Citation(doc=n, title=session.title_for(c.doc_id), page=c.page, section=c.section)
        if cit not in out:
            out.append(cit)
    return out


_raw_log_lock = threading.Lock()


def log_raw_reply(path: Path, session_id: str, step: int | str, finish_reason: str | None,
                  reply: str, error: str | None) -> None:
    """Append one unparseable LLM reply to ``path`` (timestamp, step, finish_reason, text).

    Never raises: a failing debug log must not break the agent turn.
    """
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    entry = (
        f"=== {stamp} session={session_id} step={step} finish_reason={finish_reason} chars={len(reply)}\n"
        f"error: {error}\n{reply if reply else '<empty reply>'}\n\n"
    )
    try:
        with _raw_log_lock:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("a", encoding="utf-8") as fh:
                fh.write(entry)
    except OSError as exc:
        log.warning("Could not write raw reply log %s: %s", path, exc)


def _is_tool_call_400(exc: Exception) -> bool:
    """True for Groq's 400 when gpt-oss emits a native tool call on a no-tools request."""
    return isinstance(exc, openai.BadRequestError) and any(m in str(exc) for m in _TOOL_CALL_400)


def groq_final_answer(
    llm: LLM,
    messages: list[dict[str, str]],
    fallback: Callable[[], str],
    **gen_kwargs: Any,
) -> str:
    """One agent completion that survives Groq's "Tool choice is none, but model called a tool" 400.

    The agent sends no ``tools``, which Groq treats as ``tool_choice="none"``; gpt-oss still
    sometimes emits a native tool call and Groq rejects the reply. The history is plain text
    (no ``tool_calls`` / ``role="tool"`` messages), so no flattening is needed.

    Args:
        llm: Chat model.
        messages: Conversation so far (not modified).
        fallback: Builds a deterministic answer from this turn's tool results.
        **gen_kwargs: Passed to ``llm.generate`` (``max_tokens``, ``temperature``, ``stop``).

    Returns:
        The model's reply; on a second failure ``"Final Answer: " + fallback()``. Never raises
        for this error (other errors propagate unchanged).
    """
    try:
        return llm.generate(messages, **gen_kwargs)
    except Exception as exc:  # noqa: BLE001 — only the tool-call 400 is handled
        if not _is_tool_call_400(exc):
            raise
        log.warning("Groq rejected a native tool call; retrying in plain text: %s", exc)
    retry = [*messages, {"role": "user", "content": FINAL_RETRY_PROMPT}]
    try:
        reply = llm.generate(retry, **gen_kwargs)
        # We asked for plain text, so a reply without the ReAct markers is the final answer itself.
        if reply.strip() and "Final Answer:" not in reply and "Action:" not in reply:
            reply = "Final Answer: " + reply.strip()
        return reply
    except Exception as exc:  # noqa: BLE001
        if not _is_tool_call_400(exc):
            raise
        log.warning("Groq retry also failed; using deterministic fallback answer: %s", exc)
    return "Final Answer: " + fallback()


def fallback_answer(tools: dict[str, Tool], steps: list[AgentStep]) -> str:
    """Deterministic answer from this turn's tool results (papers list for paper_search)."""
    papers: list[PaperRef] = getattr(tools.get(PAPER_TOOL), "papers", [])
    if papers:
        lines = ["Here are the papers I found:", ""]
        for p in papers:
            authors = ", ".join(p.authors[:3]) + (" et al." if len(p.authors) > 3 else "")
            pdf = f" [PDF]({p.pdf_url})" if p.pdf_url else ""
            lines.append(f"- [{p.title}]({p.url}) ({p.year or 'n.d.'}){' — ' + authors if authors else ''}{pdf}")
        return "\n".join(lines)
    found = [f"- {s.tool}: {s.observation}" for s in steps[-3:] if s.tool]
    if found:
        return "The model could not write a final answer. Latest tool results:\n" + "\n".join(found)
    return "The model could not produce an answer for this request. Please try again."


def fit_to_budget(messages: list[dict[str, str]], budget: int) -> list[dict[str, str]]:
    """A copy of ``messages`` whose prompt fits in ``budget`` tokens.

    Order of cuts: (1) past-chat history pairs, oldest first; (2) older tool results, cut to
    ``OLD_OBS_CHARS``; (3) the latest tool result, halved until it fits. The system prompt, the
    current user message and the model's own replies are never removed.

    Args:
        messages: System prompt, history pairs, the ``CURRENT user message``, then this turn's steps.
        budget: Prompt-token budget (tiktoken ``cl100k_base`` estimate).

    Returns:
        The trimmed copy (``messages`` itself is not modified).
    """
    msgs = [dict(m) for m in messages]
    total = sum(count_tokens(m["content"]) for m in msgs)
    if total <= budget:
        return msgs
    before = total
    cur = next((i for i, m in enumerate(msgs) if m["content"].startswith(CURRENT_PREFIX)), 1)
    while total > budget and cur >= 3:  # history = msgs[1:cur], user/assistant pairs
        total -= count_tokens(msgs[1]["content"]) + count_tokens(msgs[2]["content"])
        del msgs[1:3]
        cur -= 2
    obs = [i for i in range(cur + 1, len(msgs)) if msgs[i]["content"].startswith(OBS_PREFIX)]
    for i in obs[:-1]:
        if total <= budget:
            break
        old = msgs[i]["content"]
        msgs[i]["content"] = truncate(old, OLD_OBS_CHARS)
        total += count_tokens(msgs[i]["content"]) - count_tokens(old)
    if obs and total > budget:
        i = obs[-1]
        while total > budget and len(msgs[i]["content"]) > OLD_OBS_CHARS:
            old = msgs[i]["content"]
            msgs[i]["content"] = truncate(old, len(old) // 2)
            total += count_tokens(msgs[i]["content"]) - count_tokens(old)
    log.info("Request trimmed to the token budget: %d -> %d prompt tokens (budget %d)", before, total, budget)
    return msgs


class ReActAgent:
    """Runs one ReAct conversation turn per :meth:`chat` call.

    Args:
        llm: Chat model. Defaults to :func:`get_llm`.
        store: Session persistence. Defaults to ``SessionStore()``.
        tool_factory: Builds the tools for a session. Defaults to :func:`default_tools`.
        max_steps: Tool-step limit. Defaults to ``settings.agent_max_steps``.
        history_messages: Past messages (2 per turn) in the prompt. Defaults to ``settings.agent_history_messages``.
        history_max_tokens: Token cap on that history (oldest dropped first). Defaults to
            ``settings.agent_history_max_tokens``.
        router: Fine-tuned endpoint router for PDF answers. Defaults to :func:`get_router`.
        raw_log_path: Where unparseable replies are logged. Defaults to ``settings.agent_raw_log``.
    """

    def __init__(
        self,
        llm: LLM | None = None,
        store: SessionStore | None = None,
        tool_factory: Callable[[Session], list[Tool]] | None = None,
        max_steps: int | None = None,
        history_messages: int | None = None,
        history_max_tokens: int | None = None,
        router: FinetunedRouter | None = None,
        raw_log_path: str | Path | None = None,
    ) -> None:
        settings = get_settings()
        self.llm: LLM = llm or get_llm()
        self.store: SessionStore = store or SessionStore()
        self.tool_factory = tool_factory or default_tools
        self.max_steps: int = max_steps if max_steps is not None else settings.agent_max_steps
        self.history_messages: int = (
            history_messages if history_messages is not None else settings.agent_history_messages)
        self.history_max_tokens: int = (
            history_max_tokens if history_max_tokens is not None else settings.agent_history_max_tokens)
        self.router: FinetunedRouter = router or get_router()
        self.raw_log_path: Path = Path(raw_log_path or settings.agent_raw_log)
        self.step_max_tokens: int = settings.agent_step_max_tokens
        self.rewrite_max_tokens: int = settings.agent_rewrite_max_tokens
        self.obs_max_chars: int = settings.agent_obs_max_chars
        self.request_token_budget: int = settings.agent_request_token_budget
        # Test doubles may not accept ``stop``; only pass it to LLMs that do.
        self._gen_kwargs: dict[str, Any] = (
            {"stop": STOP} if "stop" in inspect.signature(self.llm.generate).parameters else {}
        )

    def _generate(self, messages: list[dict[str, str]], fallback: Callable[[], str] | None = None) -> str:
        return groq_final_answer(
            self.llm, fit_to_budget(messages, self.request_token_budget), fallback or (lambda: fallback_answer({}, [])),
            max_tokens=self.step_max_tokens, temperature=0.0, **self._gen_kwargs,
        )

    def _step_reply(
        self, messages: list[dict[str, str]], session_id: str, step: int | str,
        notes: list[AgentNote] | None = None, at_step: int = 0,
        fallback: Callable[[], str] | None = None,
    ) -> tuple[str, ParsedReply]:
        """Generate and parse one reply; re-ask once (not a new step) if it has no Action / Final Answer.

        Appends the assistant reply (and the re-ask exchange, if any) to ``messages``; a re-ask
        is recorded in ``notes`` at ``at_step``.
        """
        reply = self._generate(messages, fallback)
        parsed = parse_reply(reply)
        if parsed.incomplete:
            self._log_unparsed(session_id, step, reply, parsed.error)
            if notes is not None:
                finish = getattr(self.llm, "last_finish_reason", None)
                notes.append(AgentNote(step=at_step, kind="reask", text=truncate(
                    f"Reply had no Action or Final Answer (finish_reason={finish}); asked to continue.\n"
                    f"Reply: {reply.strip() or '<empty>'}", NOTE_CHARS)))
            first_thought = parsed.thought
            messages.append({"role": "assistant", "content": _OBS_RE.split(reply, maxsplit=1)[0].strip() or "(no reply)"})
            messages.append({"role": "user", "content": CONTINUE_PROMPT})
            reply = self._generate(messages, fallback)
            parsed = parse_reply(reply)
            parsed.thought = parsed.thought or first_thought
            step = f"{step}-reask"
        if parsed.error is not None:
            self._log_unparsed(session_id, step, reply, parsed.error)
        messages.append({"role": "assistant", "content": _OBS_RE.split(reply, maxsplit=1)[0].strip() or "(no reply)"})
        return reply, parsed

    def _log_unparsed(self, session_id: str, step: int | str, reply: str, error: str | None) -> None:
        finish_reason = getattr(self.llm, "last_finish_reason", None)
        log.warning("Step %s reply did not parse (finish_reason=%s): %s", step, finish_reason, error)
        log_raw_reply(self.raw_log_path, session_id, step, finish_reason, reply, error)

    def _messages(self, session: Session, tools: dict[str, Tool], message: str) -> list[dict[str, str]]:
        listing = "\n".join(f"- {t.name}{t.signature()}: {t.description}" for t in tools.values())
        names = sorted(set(load_doc_names(chat_id=session.session_id).values()))  # this chat's documents
        documents = ", ".join(names[:MAX_LISTED_DOCS]) + (" ..." if len(names) > MAX_LISTED_DOCS else "")
        messages = [{"role": "system", "content": SYSTEM_TEMPLATE.format(tools=listing, documents=documents or "none")}]
        for turn in self._history(session):
            messages += [{"role": "user", "content": turn.user}, {"role": "assistant", "content": turn.assistant}]
        messages.append({"role": "user", "content": CURRENT_PREFIX + message})
        return messages

    def _history(self, session: Session) -> list[Turn]:
        """This chat's past turns (final answers only), trimmed to the message and token caps."""
        return trim_history(session.turns, self.history_messages, self.history_max_tokens)

    def _standalone_question(self, session: Session, message: str) -> str:
        """Rewrite a follow-up into a standalone question with one short LLM call.

        Returns ``message`` unchanged if there is no history or the call fails.
        """
        history = self._history(session)
        if not history:
            return message
        convo = "\n\n".join(f"User: {t.user}\nAssistant: {truncate(t.assistant, REWRITE_ANSWER_CHARS)}" for t in history)
        prompt = [{"role": "system", "content": REWRITE_PROMPT},
                  {"role": "user", "content": f"Conversation:\n{convo}\n\nLatest message: {message}"}]
        try:
            reply = self.llm.generate(prompt, max_tokens=self.rewrite_max_tokens, temperature=0.0)
        except Exception as exc:  # noqa: BLE001 — retrieval still works with the raw message
            log.warning("Standalone-question rewrite failed; using the raw message: %s", exc)
            return message
        lines = [ln.strip().strip('"') for ln in (reply or "").splitlines() if ln.strip()]
        return lines[0] if lines else message

    @staticmethod
    def _run_tool(tools: dict[str, Tool], call: ToolCall) -> str:
        tool = tools.get(call.tool)
        if tool is None:
            return f"Error: unknown tool '{call.tool}'. Available tools: {', '.join(tools)}."
        tool.model_used = None
        try:
            return tool(call.args)
        except ValidationError as exc:
            errs = "; ".join(f"{'.'.join(map(str, e['loc'])) or 'args'}: {e['msg']}" for e in exc.errors())
            return f"Error: invalid args for {call.tool}: {errs}. Expected {tool.signature()}."
        except Exception as exc:  # noqa: BLE001 — tool failures become observations
            log.exception("Tool %s failed", call.tool)
            return f"Error: {call.tool} failed: {exc}"

    def chat(self, session_id: str, message: str) -> AgentResult:
        """Answer ``message`` in ``session_id``'s conversation and save the turn.

        If every agent model fails, :meth:`_degraded` answers instead (no exception).

        Raises:
            ValueError: If ``session_id`` is malformed.
        """
        try:
            return self._chat_turn(session_id, message)
        except AllModelsFailedError as exc:
            return self._degraded(session_id, message, exc)

    def _chat_turn(self, session_id: str, message: str) -> AgentResult:
        if hasattr(self.llm, "begin_turn"):
            self.llm.begin_turn()
        session = self.store.load(session_id)
        tools = {t.name: t for t in self.tool_factory(session)}
        messages = self._messages(session, tools, message)
        steps: list[AgentStep] = []
        notes: list[AgentNote] = []
        answer: str | None = None
        python_outputs: list[str] = []
        tools_used: set[str] = set()
        fallback = lambda: fallback_answer(tools, steps)  # noqa: E731
        standalone: str | None = None  # follow-up rewritten with this chat's history, computed lazily
        rag_rewritten = False

        for _ in range(self.max_steps):
            step_start = time.perf_counter()
            _reply, parsed = self._step_reply(messages, session_id, len(steps) + 1, notes, len(steps) + 1, fallback)
            if parsed.final is not None:
                answer = parsed.final
                if parsed.thought:
                    notes.append(AgentNote(step=len(steps) + 1, kind="final_thought", text=truncate(parsed.thought, NOTE_CHARS)))
                break
            model_used = None
            if parsed.action is not None:
                if parsed.action.tool in PDF_TOOLS and standalone is None:
                    standalone = self._standalone_question(session, message)
                    if standalone != message:
                        notes.append(AgentNote(step=len(steps) + 1, kind="standalone",
                                               text=truncate(f"Standalone question: {standalone}", NOTE_CHARS)))
                if parsed.action.tool == RAG_TOOL and not rag_rewritten and standalone not in (None, message):
                    # The first retrieval of a follow-up uses the standalone question; later
                    # rag_search calls keep the agent's own query.
                    parsed.action.args = {**parsed.action.args, "query": standalone}
                    rag_rewritten = True
                observation = self._run_tool(tools, parsed.action)
                tool, args = parsed.action.tool, parsed.action.args
                model_used = getattr(tools.get(tool), "model_used", None)
                if tool in tools:
                    tools_used.add(tool)
                if tool == PYTHON_TOOL:
                    python_outputs.append(truncate(observation, self.obs_max_chars))
            else:
                observation, tool, args = f"Error: {parsed.error}", None, {}
            total_ms = round((time.perf_counter() - step_start) * 1000, 1)
            log.info("Agent step %d: tool=%s total_ms=%.0f", len(steps) + 1, tool, total_ms)
            images = [p.strip() for m in _FIGURES_RE.finditer(observation) for p in m.group(1).split(",")]
            steps.append(AgentStep(thought=parsed.thought, tool=tool, args=args,
                                   observation=truncate(observation, STEP_OBS_CHARS), images=images,
                                   total_ms=total_ms, model_used=model_used))
            messages.append({"role": "user", "content": OBS_PREFIX + truncate(observation, self.obs_max_chars)})

        if answer is None:
            log.info("Step limit (%d) reached; forcing a final answer", self.max_steps)
            messages.append({"role": "user", "content": FORCE_FINAL})
            notes.append(AgentNote(step=len(steps) + 1, kind="step_limit",
                                   text=f"Step limit ({self.max_steps}) reached; asked for a final answer from the observations so far."))
            reply, parsed = self._step_reply(messages, session_id, "forced-final", notes, len(steps) + 1, fallback)
            if parsed.thought:
                notes.append(AgentNote(step=len(steps) + 1, kind="final_thought", text=truncate(parsed.thought, NOTE_CHARS)))
            if parsed.final is None and parsed.error is None:  # it asked for another tool
                self._log_unparsed(session_id, "forced-final", reply, "tool call after the step limit")
            answer = parsed.final or parsed.thought or self._partial_answer(steps)

        retrieved = _unique_chunks(rc for t in tools.values() for rc in getattr(t, "retrieved", []))
        summary = getattr(tools.get(SUMMARY_TOOL), "last_summary", None)
        pdf_turn = bool(tools_used & PDF_TOOLS) and PAPER_TOOL not in tools_used
        if pdf_turn and tools_used & PDF_TOOLS == {SUMMARY_TOOL} and summary:
            # A pure summary turn: show the section-by-section summary itself, not a rewrite of it.
            routed = RoutedAnswer(answer=summary, model_used=tools[SUMMARY_TOOL].model_used or api_llm_label())
        else:
            routed = self._route_final(standalone or message, answer, pdf_turn, retrieved, python_outputs)
        usage = getattr(self.llm, "turn_usage", None)
        if usage is not None:
            log.info("Turn usage chat=%s: llm_calls=%d prompt_tokens=%d completion_tokens=%d total=%d",
                     session_id, usage["calls"], usage["prompt_tokens"], usage["completion_tokens"],
                     usage["prompt_tokens"] + usage["completion_tokens"])
        last = getattr(self.llm, "last_reply", None)
        if last is not None and routed.model_used == api_llm_label():
            routed.model_used = f"{'Groq ' if last.model.provider == 'groq' else ''}{last.model.short_name}"
        answer = routed.answer
        route = f"Final answer by {routed.model_used}"
        if routed.latency_ms is not None:
            route += f" in {routed.latency_ms / 1000:.1f}s"
        if routed.fallback_reason:
            route += f" (fallback: {routed.fallback_reason})"
        notes.append(AgentNote(step=len(steps) + 1, kind="routing", text=route))
        citations = citations_from_chunks(answer, retrieved, session) if retrieved else extract_citations(answer, session)
        session.turns.append(Turn(user=message, assistant=answer))
        self.store.save(session)
        cited_docs = {c.doc for c in citations}
        texts = [ch.text for n, ch in retrieved if n in cited_docs] or [ch.text for _, ch in retrieved]
        return AgentResult(
            answer=answer, citations=citations, steps=steps, cited_chunks=list(dict.fromkeys(texts)),
            model_used=routed.model_used, latency_ms=routed.latency_ms, fallback_reason=routed.fallback_reason,
            images=list(dict.fromkeys(p for step in steps for p in step.images)),
            papers=[p for t in tools.values() for p in getattr(t, "papers", [])],
            notes=notes,
            agent_model=last.model.short_name if last is not None else None,
            agent_fallback=bool(last and last.fallback),
        )

    def _degraded(self, session_id: str, message: str, exc: AllModelsFailedError) -> AgentResult:
        """Answer without the agent LLM: direct paper search, PDF question via the fine-tuned
        model, or a fixed "temporarily unavailable" message."""
        log.warning("All agent models failed; answering in degraded mode: %s", exc)
        session = self.store.load(session_id)
        tools = {t.name: t for t in self.tool_factory(session)}
        notes = [AgentNote(step=1, kind="degraded", text=truncate(str(exc), NOTE_CHARS))]
        steps: list[AgentStep] = []
        retrieved: list[tuple[int, Chunk]] = []
        model_used, latency = DEGRADED_LABEL, None

        def run(tool: str, args: dict[str, Any]) -> str:
            obs = self._run_tool(tools, ToolCall(tool=tool, args=args))
            steps.append(AgentStep(thought="Degraded mode: agent model unavailable", tool=tool, args=args,
                                   observation=truncate(obs, STEP_OBS_CHARS)))
            return obs

        if PAPER_TOOL in tools and PAPER_QUERY_RE.search(message):
            query = _PAPER_PREFIX_RE.sub("", message).strip(" ?.!") or message
            obs = run(PAPER_TOOL, {"query": query})
            if getattr(tools[PAPER_TOOL], "papers", []):
                answer = f'The agent model is temporarily unavailable, so here are the results of a direct paper search for "{query}".'
            else:
                answer = f'The agent model is temporarily unavailable, and a direct paper search for "{query}" returned: {obs}'
            model_used = f"paper_search ({DEGRADED_LABEL})"
        elif RAG_TOOL in tools and load_doc_names(chat_id=session_id):
            run(RAG_TOOL, {"query": message})
            retrieved = _unique_chunks(getattr(tools[RAG_TOOL], "retrieved", []))
            if not retrieved:
                answer = "The agent model is temporarily unavailable, and no passages in your uploaded PDFs matched this question."
            else:
                result = self.router.complete(build_pdf_prompt(message, retrieved, []),
                                              max_tokens=ANSWER_MAX_TOKENS, temperature=ANSWER_TEMPERATURE)
                if result.text is not None:
                    answer, model_used, latency = result.text, FINETUNED_LABEL, result.latency_ms
                else:
                    answer = ("The agent model is temporarily unavailable (rate limit), and the fine-tuned PDF model "
                              f"is unreachable ({result.fallback_reason}). Please try again in a minute.")
                    retrieved = []
        else:
            answer = AGENT_UNAVAILABLE
        notes.append(AgentNote(step=len(steps) + 1, kind="routing", text=f"Final answer by {model_used}"))
        citations = citations_from_chunks(answer, retrieved, session) if retrieved else []
        session.turns.append(Turn(user=message, assistant=answer))
        self.store.save(session)
        return AgentResult(
            answer=answer, citations=citations, steps=steps, model_used=model_used, latency_ms=latency,
            cited_chunks=[ch.text for _, ch in retrieved],
            papers=[p for t in tools.values() for p in getattr(t, "papers", [])],
            notes=notes, degraded=True,
        )

    @staticmethod
    def _partial_answer(steps: list[AgentStep]) -> str:
        """Last-resort answer when the forced final reply is empty: the latest observations."""
        found = [f"- {s.tool}: {s.observation}" for s in steps[-3:] if s.tool]
        return "I reached the step limit before finishing. What I found so far:\n" + ("\n".join(found) or "- nothing yet")

    def _route_final(
        self, message: str, draft: str, pdf_turn: bool,
        retrieved: list[tuple[int, Chunk]], python_outputs: list[str],
    ) -> RoutedAnswer:
        """The fine-tuned model answers only PDF turns (rag_search / summarize_papers and no
        paper_search); every other turn keeps the Groq answer unchanged."""
        if not pdf_turn:
            return RoutedAnswer(answer=draft, model_used=api_llm_label())
        if not retrieved:
            return RoutedAnswer(answer=draft, model_used=api_llm_label(), fallback_reason="no PDF chunks retrieved")
        return generate_pdf_answer(message, retrieved, python_outputs, draft, router=self.router)
